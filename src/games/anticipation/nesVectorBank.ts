/**
 * Checks if a word resolves directly to a concrete standalone NES picture motif
 * (excluding vague multi-word holiday/activity aliases like "New Year's Day" -> sun).
 */
export function hasDirectNesPicture(english: string): boolean {
  const norm = normalizeWordKey(english);
  if (!norm) return false;
  if (NES_MOTIFS[norm] || DIRECT_OBJECT_ALIASES[norm]) return true;
  const compact = norm.replace(/[\s\-]+/g, '');
  if (NES_MOTIFS[compact]) return true;
  const singular = norm.endsWith('s') && norm.length > 3 ? norm.slice(0, -1) : '';
  if (singular && (NES_MOTIFS[singular] || DIRECT_OBJECT_ALIASES[singular])) return true;
  const esSingular = norm.endsWith('es') && norm.length > 4 ? norm.slice(0, -2) : '';
  if (esSingular && NES_MOTIFS[esSingular]) return true;
  return false;
}

/**
 * Checks if a word resolves cleanly to a curated 1988 NES-style minimalist picture vector
 * (excludes pure single letters or bare numbers so mixed unit decks favor rich illustrations).
 */
export function hasCuratedNesPicture(english: string): boolean {
  const norm = normalizeWordKey(english);
  if (!norm) return false;
  if (NES_MOTIFS[norm] || ALIASES[norm]) return true;
  const singular = norm.endsWith('s') && norm.length > 3 ? norm.slice(0, -1) : '';
  if (singular && (NES_MOTIFS[singular] || ALIASES[singular])) return true;
  const tokens = norm.split(' ');
  for (let i = tokens.length - 1; i >= 0; i--) {
    const tk = tokens[i];
    if (NES_MOTIFS[tk] || ALIASES[tk]) return true;
  }
  return false;
}

/**
 * Checks if a word resolves cleanly to a curated 1988 NES-style minimalist polyline vector
 * (including concrete pictures AND clean alphabet/number glyph strokes).
 */
export function resolveCuratedNesStrokes(english: string): SketchPoint[][] | null {
  const rawTrimmed = (english || '').trim();
  if (!rawTrimmed) return null;

  // Single alphabet letter ("A", "b")
  if (/^[a-zA-Z]$/.test(rawTrimmed)) {
    const glyph = GLYPH_STROKES[rawTrimmed.toUpperCase()];
    if (glyph) return toSketchStrokes(glyph);
  }

  const norm = normalizeWordKey(english);
  if (!norm) return null;

  // 0. Number words ("twenty", "five", "one hundred")
  if (NUMBER_WORD_MAP[norm]) {
    const numStrokes = buildMultiDigitStrokes(NUMBER_WORD_MAP[norm]);
    if (numStrokes) return toSketchStrokes(numStrokes);
  }

  // 1. Direct or alias match
  const directKey = NES_MOTIFS[norm] ? norm : ALIASES[norm];
  if (directKey && NES_MOTIFS[directKey]) {
    return toSketchStrokes(NES_MOTIFS[directKey]);
  }

  // 2. Simple plural stem removal ("bikes" -> "bike")
  const singular = norm.endsWith('s') && norm.length > 3 ? norm.slice(0, -1) : '';
  const singularKey = singular && (NES_MOTIFS[singular] ? singular : ALIASES[singular]);
  if (singularKey && NES_MOTIFS[singularKey]) {
    return toSketchStrokes(NES_MOTIFS[singularKey]);
  }

  // 3. Token keyword match inside short phrases (e.g. "play basketball" -> "basketball", "blue bag" -> "bag")
  const tokens = norm.split(' ');
  for (let i = tokens.length - 1; i >= 0; i--) {
    const tk = tokens[i];
    const hit = NES_MOTIFS[tk] ? tk : ALIASES[tk];
    if (hit && NES_MOTIFS[hit]) {
      return toSketchStrokes(NES_MOTIFS[hit]);
    }
  }

  return null;
}

export function hasCuratedNesMotif(english: string): boolean {
  return resolveCuratedNesStrokes(english) !== null;
}
