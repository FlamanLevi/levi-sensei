/**
 * Hand-crafted 1988 NES-style minimalist geometric vector motifs.
 * Uses crisp low-vertex angular polylines (~6-26 segments) inspired directly
 * by classic NES Anticipation puzzles (e.g., 5-line cake wedge, 12-line trumpet),
 * matching MEXT elementary English vocabulary without noisy cartoon shading.
 */

type Coord = [number, number];
type PolyList = Coord[][];

function poly(...pts: Coord[]): Coord[] {
  return pts;
}

function rect(x: number, y: number, w: number, h: number): Coord[] {
  return [
    [x, y],
    [x + w, y],
    [x + w, y + h],
    [x, y + h],
    [x, y],
  ];
}

function ngon(cx: number, cy: number, rx: number, ry: number, sides = 10, startRad = 0): Coord[] {
  const pts: Coord[] = [];
  for (let i = 0; i <= sides; i++) {
    const a = startRad + (Math.PI * 2 * i) / sides;
    pts.push([
      Math.max(0.08, Math.min(0.92, +(cx + Math.cos(a) * rx).toFixed(3))),
      Math.max(0.08, Math.min(0.92, +(cy + Math.sin(a) * ry).toFixed(3))),
    ]);
  }
  return pts;
}

function arcPts(cx: number, cy: number, rx: number, ry: number, startRad: number, endRad: number, steps = 7): Coord[] {
  const pts: Coord[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = startRad + ((endRad - startRad) * i) / steps;
    pts.push([
      Math.max(0.08, Math.min(0.92, +(cx + Math.cos(a) * rx).toFixed(3))),
      Math.max(0.08, Math.min(0.92, +(cy + Math.sin(a) * ry).toFixed(3))),
    ]);
  }
  return pts;
}

