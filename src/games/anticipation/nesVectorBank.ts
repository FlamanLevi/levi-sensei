function buildMultiDigitStrokes(digits: string): PolyList | null {
  const chars = digits.split('').filter((c) => GLYPH_STROKES[c]);
  if (chars.length === 0) return null;
  if (chars.length === 1) return GLYPH_STROKES[chars[0]];
  const res: PolyList = [];
  const slotW = 0.82 / chars.length;
  chars.forEach((ch, idx) => {
    const base = GLYPH_STROKES[ch];
    const startX = 0.09 + idx * slotW;
    base.forEach((stroke) => {
      res.push(
        stroke.map(([x, y]) => [
          +(startX + (x - 0.16) * (slotW / 0.68)).toFixed(3),
          y,
        ])
      );
    });
  });
  return res;
}

function normalizeWordKey(raw: string): string {
  return (raw || '')
    .trim()
    .toLowerCase()
    .replace(/^(a|an|the)\s+/i, '')
    .replace(/[.!?,'"]/g, '')
    .replace(/\s+/g, ' ');
}

function toSketchStrokes(polyList: PolyList): SketchPoint[][] {
  return polyList.map((polyCoords) =>
    polyCoords.map(([x, y]) => ({
      x: Math.max(0.06, Math.min(0.94, x)),
      y: Math.max(0.06, Math.min(0.94, y)),
    }))
  );
}

